/**
 * hosts/README.md — the generated index of the per-host output.
 *
 * Pins three things: the README is a deterministic function of the plan (no clock, no host
 * path); it says what a maintainer needs (hosts, mirrors, agent × host matrix, every warning);
 * and it is build output like any other file (ledgered, drift-checked) that only a FULL build
 * owns — a targeted build must neither rewrite, prune nor report it.
 */

import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { tmpdir } from "node:os";
import { check, lintBuild, plan, readManifest, write } from "../../../src/index.js";
import {
  HOSTS_README_PATH,
  HOSTS_README_TARGET,
  renderHostsReadme,
} from "../../../src/core/HostsReadme.js";
import { BUILD_TARGETS, TARGET_LAYOUT } from "../../../src/core/BuildPipeline.js";

let root: string;

function canonicalAgent(id: string, targets: readonly string[], extra: readonly string[] = []): string {
  const overrides = targets.includes("claude-code")
    ? ["  overrides:", "    claude-code:", "      tools: [Read]"]
    : [];
  return [
    "---",
    `name: ${id}`,
    `description: Fixture agent ${id}.`,
    "mode: subagent",
    ...extra,
    "permission:",
    "  read:",
    '    "*": "allow"',
    "oac:",
    `  id: ${id}`,
    `  name: ${id}`,
    "  category: subagents/test",
    "  type: subagent",
    '  version: "1.0.0"',
    "  author: opencode",
    "  targets:",
    ...targets.map((target) => `    - ${target}`),
    ...overrides,
    "---",
    "",
    `# ${id}`,
    "",
    "Body.",
    "",
  ].join("\n");
}

function put(relativePath: string, content: string): void {
  const absolute = join(root, relativePath);
  mkdirSync(dirname(absolute), { recursive: true });
  writeFileSync(absolute, content, "utf-8");
}

const BASE_REGISTRY = {
  version: "1.0.0",
  metadata: { lastUpdated: "2026-01-01" },
  components: { agents: [], subagents: [], contexts: [] },
  profiles: {},
};

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "oac-hosts-readme-"));
  put("registry.json", `${JSON.stringify(BASE_REGISTRY, null, 2)}\n`);
  put("registry.v1.json", `${JSON.stringify(BASE_REGISTRY, null, 2)}\n`);
  put("content/agents/subagents/test/alpha.md", canonicalAgent("alpha", ["opencode"]));
  // temperature has no Claude Code equivalent: the claude-code build warns about it.
  put(
    "content/agents/subagents/test/beta.md",
    canonicalAgent("beta", ["opencode", "claude-code"], ["temperature: 0.1"]),
  );
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

const readmeOf = async (): Promise<string> => {
  const built = await plan({ root });
  const file = built.files.find((f) => f.path === HOSTS_README_PATH);
  expect(file, "full build plans hosts/README.md").toBeDefined();
  expect(file!.target).toBe(HOSTS_README_TARGET);
  return file!.content;
};

describe("hosts/README.md contents", () => {
  it("carries the do-not-edit banner and the how-it-works links", async () => {
    const readme = await readmeOf();
    expect(readme.startsWith("<!-- GENERATED by `oac build`")).toBe(true);
    expect(readme).toMatch(/Generated — do not edit/);
    expect(readme).toMatch(/content\/agents\/\*\*/);
    expect(readme).toMatch(/<!-- oac:only <host> -->/);
    expect(readme).toContain("(../docs/lessons-learnt/decisions.md)");
    expect(readme).toContain("(../docs/features/opencode-v1-and-v2.md)");
  });

  it("lists every host with its folder, agent count, live mirror and reader", async () => {
    const readme = await readmeOf();
    expect(readme).toContain("| `opencode` | `hosts/opencode/` | 2 | 0 | `.opencode/agent/` |");
    expect(readme).toContain("| `opencode-v1` | `hosts/opencode-v1/` | 2 | 0 | — |");
    expect(readme).toContain("| `claude-code` | `hosts/claude-code/` | 1 | 1 | `plugins/claude-code/agents/` |");
    expect(readme).toContain("registry.json");
    expect(readme).toContain("registry.v1.json");
    expect(readme).toContain(".claude-plugin/marketplace.json");
  });

  it("has an agent × host matrix with — for hosts an agent does not target", async () => {
    const readme = await readmeOf();
    expect(readme).toContain(
      "| `alpha` | `subagents/test/alpha.md` | `alpha.md` | `subagents/test/alpha.md` | — | 0 |",
    );
    expect(readme).toContain(
      "| `beta` | `subagents/test/beta.md` | `beta.md` | `subagents/test/beta.md` | `beta.md` | 1 |",
    );
  });

  it("groups every degradation warning per host per agent", async () => {
    const built = await plan({ root });
    const readme = built.files.find((f) => f.path === HOSTS_README_PATH)!.content;
    const claude = readme.slice(readme.indexOf("### `claude-code`\n\n"));

    expect(claude).toContain("- **`beta`** → `hosts/claude-code/agents/beta.md`");
    for (const warning of built.warnings) {
      expect(readme).toContain(warning.reason.replace(/^\s*⚠️?\s*/u, "").trim());
    }
    expect(built.warnings.length).toBeGreaterThan(0);
    expect(readme).toMatch(/### `opencode`\n\nNone/);
  });

  it("is deterministic and free of timestamps and absolute paths", async () => {
    const first = await readmeOf();
    const second = await readmeOf();
    expect(second).toBe(first);
    expect(first).not.toContain(root);
    expect(first).not.toMatch(/\d{4}-\d{2}-\d{2}T\d{2}:/);
    expect(first.endsWith("\n")).toBe(true);
  });

  it("is a pure function of its input", () => {
    const input = { files: [], agents: [], hosts: BUILD_TARGETS, layout: TARGET_LAYOUT };
    expect(renderHostsReadme(input)).toBe(renderHostsReadme(input));
  });

  it("is not linted", async () => {
    const built = await plan({ root });
    const targets = lintBuild(built.files).map((result) => result.target);
    expect(targets).not.toContain(HOSTS_README_TARGET);
  });
});

describe("hosts/README.md as build output", () => {
  it("is written, ledgered, and a second build rewrites nothing", async () => {
    const first = write(await plan({ root }), { root });
    expect(first.changed).toContain(HOSTS_README_PATH);
    expect(readManifest(root).files[HOSTS_README_PATH]?.target).toBe(HOSTS_README_TARGET);

    const second = write(await plan({ root }), { root });
    expect(second.changed).toEqual([]);
    expect(check(await plan({ root }), { root })).toEqual([]);
  });

  it("a stale or hand-edited README is drift under --check", async () => {
    write(await plan({ root }), { root });
    put(HOSTS_README_PATH, "# hand edited\n");
    expect(check(await plan({ root }), { root })).toEqual([
      { path: HOSTS_README_PATH, status: "modified" },
    ]);

    rmSync(join(root, HOSTS_README_PATH));
    expect(check(await plan({ root }), { root })).toEqual([
      { path: HOSTS_README_PATH, status: "missing" },
    ]);
  });

  it("goes stale when an agent changes, and the full build refreshes it", async () => {
    write(await plan({ root }), { root });
    put("content/agents/subagents/test/gamma.md", canonicalAgent("gamma", ["opencode"]));

    const drift = check(await plan({ root }), { root });
    expect(drift).toContainEqual({ path: HOSTS_README_PATH, status: "modified" });

    write(await plan({ root }), { root });
    expect(readFileSync(join(root, HOSTS_README_PATH), "utf-8")).toContain("| `gamma` |");
  });

  it("a targeted build neither emits, rewrites, prunes nor reports it (carried forward)", async () => {
    write(await plan({ root }), { root });
    const before = readFileSync(join(root, HOSTS_README_PATH), "utf-8");
    const entry = readManifest(root).files[HOSTS_README_PATH];

    for (const targets of [["claude-code"], ["opencode"], ["opencode", "opencode-v1"]] as const) {
      const targeted = await plan({ root, targets: [...targets] });
      expect(targeted.files.some((f) => f.path === HOSTS_README_PATH), targets.join(",")).toBe(false);
      expect(check(targeted, { root }), targets.join(",")).toEqual([]);

      const result = write(targeted, { root });
      expect(result.removed).not.toContain(HOSTS_README_PATH);
      expect(result.changed).not.toContain(HOSTS_README_PATH);
      expect(readFileSync(join(root, HOSTS_README_PATH), "utf-8")).toBe(before);
      expect(readManifest(root).files[HOSTS_README_PATH]).toEqual(entry);
    }
  });

  it("is built by a full build even when the registries are skipped", async () => {
    const built = await plan({ root, skipRegistry: true });
    expect(built.files.some((f) => f.path === HOSTS_README_PATH)).toBe(true);
    expect(built.owns).toContain(HOSTS_README_TARGET);
  });

  it("is pruned only by a full build, and only when it is still unedited", async () => {
    write(await plan({ root }), { root });
    // A full build that stops producing it (simulated with a plan without the file) prunes it.
    const full = await plan({ root });
    const without = { ...full, files: full.files.filter((f) => f.path !== HOSTS_README_PATH) };
    const result = write(without, { root });
    expect(result.removed).toEqual([HOSTS_README_PATH]);
    expect(existsSync(join(root, HOSTS_README_PATH))).toBe(false);
    expect(existsSync(join(root, "hosts"))).toBe(true);
  });
});
